/** Resolve a 4-digit Australian postcode to its STC zone, or null. */
export function zoneForPostcode(postcode: number): Zone | null {
  if (!Number.isInteger(postcode) || postcode < 0 || postcode > 9999) return null;
  for (const [from, to, zone] of POSTCODE_ZONES) {
    if (postcode >= from && postcode <= to) return zone;
  }
  return null;
}
